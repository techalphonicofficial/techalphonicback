<?php

use App\Models\ActivityLog;
use App\Support\Icons;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Schedule;

// Keeps the Next.js icon set (frontend/src/lib/icons.generated.ts) identical to App\Support\Icons.
Artisan::command('site:export-icons', function () {
    $path = base_path('../frontend/src/lib/icons.generated.ts');
    $body = "// Generated by `php artisan site:export-icons` from App\\Support\\Icons. Do not edit by hand.\n"
        .'export const ICONS: Record<string, string> = '.json_encode(Icons::PATHS, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE).";\n";
    file_put_contents($path, $body);
    $this->info('Wrote '.count(Icons::PATHS).' icons to '.$path);
})->purpose('Export the SVG icon set to the Next.js frontend');

// Requires the cron entry: * * * * * php /path/to/artisan schedule:run >> /dev/null 2>&1
Schedule::command('content:publish-scheduled')->everyMinute()->withoutOverlapping();
Schedule::command('queue:prune-failed --hours=168')->daily();
Schedule::command('sanctum:prune-expired --hours=24')->daily();
Schedule::call(fn () => ActivityLog::where('created_at', '<', now()->subMonths(6))->delete())->weekly()->name('prune-activity-log');
